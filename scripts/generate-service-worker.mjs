import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const TEMPLATE = String.raw`// Generated by scripts/generate-service-worker.mjs.
const VERSION = __BUILD_ID__;
const SHELL_CACHE = "padelclash-shell-" + VERSION;
const OFFLINE_SHELL = "/offline";
const NEVER_HANDLE = [/^\/api\//, /^\/admin/, /^\/join\//];

self.addEventListener("install", (event) => {
  event.waitUntil(installShell());
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys
        .filter((key) => key.startsWith("padelclash-") && key !== SHELL_CACHE)
        .map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (NEVER_HANDLE.some((pattern) => pattern.test(url.pathname))) return;

  if (request.mode === "navigate") {
    event.respondWith(navigate(request, url.pathname));
    return;
  }

  if (url.pathname.startsWith("/_next/static/")) {
    event.respondWith(caches.match(request).then((cached) => cached || fetch(request)));
  }
});

async function installShell() {
  const response = await fetch(OFFLINE_SHELL, { cache: "reload" });
  if (!response.ok) throw new Error("Offline shell returned " + response.status);
  const html = await response.clone().text();
  const assets = Array.from(html.matchAll(/(?:src|href)=["']([^"']+)["']/g))
    .map((match) => match[1])
    .filter((url) => url.startsWith("/_next/static/"));
  const cache = await caches.open(SHELL_CACHE);
  await cache.put(OFFLINE_SHELL, response);
  await cache.addAll(Array.from(new Set(assets)));
}

async function navigate(request, pathname) {
  try {
    return await fetch(request);
  } catch {
    if (pathname === "/" || pathname === "/log" || pathname === OFFLINE_SHELL) {
      const shell = await caches.match(OFFLINE_SHELL);
      if (shell) return shell;
    }
    return new Response(
      "<h1>Offline</h1><p>This private page needs a connection.</p>",
      { status: 503, headers: { "Content-Type": "text/html; charset=utf-8" } },
    );
  }
}
`;

export function renderServiceWorker(buildId) {
  return TEMPLATE.replace("__BUILD_ID__", JSON.stringify(buildId));
}

async function generate() {
  const root = process.cwd();
  const buildId = (await fs.readFile(path.join(root, ".next", "BUILD_ID"), "utf8")).trim();
  await fs.writeFile(
    path.join(root, "public", "sw.js"),
    renderServiceWorker(buildId),
    "utf8",
  );
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  await generate();
}
