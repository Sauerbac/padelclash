import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const TEMPLATE = String.raw`// Generated by scripts/generate-service-worker.mjs.
const VERSION = __BUILD_ID__;
const SHELL_CACHE = "padelclash-shell-" + VERSION;
const NAVIGATION_CACHE = "padelclash-navigation-" + VERSION;
const OFFLINE_SHELL = "/offline";
const SHELL_ASSETS = ["/logo.svg"];
const NAVIGATION_DEADLINE_MS = 5_000;
const NEVER_HANDLE = [/^\/api\//, /^\/admin/, /^\/join\//];

self.addEventListener("install", (event) => {
  event.waitUntil(installShell());
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys
        .filter((key) => key.startsWith("padelclash-") && key !== SHELL_CACHE)
        .map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (NEVER_HANDLE.some((pattern) => pattern.test(url.pathname))) return;

  if (request.mode === "navigate") {
    let fallbackShown = false;
    const networkCompletion = takeRecoveredNavigation(url.pathname)
      .then((recovered) => recovered || fetch(request).then(async (response) => {
        if (fallbackShown && isUsableNavigation(response)) {
          const cache = await caches.open(NAVIGATION_CACHE);
          await cache.put(navigationCacheKey(url.pathname), response.clone());
          await notifyNavigationReady(url.pathname);
        }
        return response;
      }));
    event.waitUntil(networkCompletion.then(() => undefined, () => undefined));
    event.respondWith(navigate(networkCompletion, url.pathname, () => {
      fallbackShown = true;
    }));
    return;
  }

  if (SHELL_ASSETS.includes(url.pathname) || url.pathname.startsWith("/_next/static/")) {
    event.respondWith(caches.match(request).then((cached) => cached || fetch(request)));
  }
});

self.addEventListener("message", (event) => {
  if (event.data?.type !== "navigation-status") return;
  event.waitUntil(
    caches.open(NAVIGATION_CACHE)
      .then((cache) => cache.match(navigationCacheKey(event.data.pathname)))
      .then((response) => {
        if (response) event.source?.postMessage({
          type: "navigation-ready",
          pathname: event.data.pathname,
        });
      }),
  );
});

async function installShell() {
  const response = await fetch(OFFLINE_SHELL, { cache: "reload" });
  if (!response.ok) throw new Error("Offline shell returned " + response.status);
  const html = await response.clone().text();
  const assets = Array.from(html.matchAll(/(?:src|href)=["']([^"']+)["']/g))
    .map((match) => match[1])
    .filter((url) => url.startsWith("/_next/static/"));
  const cache = await caches.open(SHELL_CACHE);
  await cache.put(OFFLINE_SHELL, response);
  await cache.addAll(Array.from(new Set(assets)));
  await cache.addAll(SHELL_ASSETS);
}

async function navigate(network, pathname, markFallbackShown) {
  const deadline = new Promise((resolve) =>
    setTimeout(() => resolve(null), NAVIGATION_DEADLINE_MS),
  );
  try {
    const response = await Promise.race([network, deadline]);
    if (response && isUsableNavigation(response)) return response;
    markFallbackShown();
    return await navigationFallback(pathname);
  } catch {
    markFallbackShown();
    return await navigationFallback(pathname);
  }
}

function navigationCacheKey(pathname) {
  return new Request(self.location.origin + "/__pc-navigation?path=" + encodeURIComponent(pathname));
}

async function takeRecoveredNavigation(pathname) {
  const cache = await caches.open(NAVIGATION_CACHE);
  const key = navigationCacheKey(pathname);
  const response = await cache.match(key);
  if (response) await cache.delete(key);
  return response;
}

function isUsableNavigation(response) {
  return response.ok && (response.headers.get("content-type") || "").includes("text/html");
}

async function navigationFallback(pathname) {
  if (pathname === "/" || pathname === "/log" || pathname === "/leaderboard" || pathname === OFFLINE_SHELL) {
    const shell = await caches.match(OFFLINE_SHELL);
    if (shell) return shell;
  }
  return new Response(
    "<h1>Offline</h1><p>This private page needs a connection.</p>",
    { status: 503, headers: { "Content-Type": "text/html; charset=utf-8" } },
  );
}

async function notifyNavigationReady(pathname) {
  for (const client of await self.clients.matchAll({ type: "window", includeUncontrolled: true })) {
    client.postMessage({ type: "navigation-ready", pathname });
  }
}
`;

export function renderServiceWorker(buildId) {
  return TEMPLATE.replace("__BUILD_ID__", JSON.stringify(buildId));
}

async function generate() {
  const root = process.cwd();
  const buildId = (await fs.readFile(path.join(root, ".next", "BUILD_ID"), "utf8")).trim();
  await fs.writeFile(
    path.join(root, "public", "sw.js"),
    renderServiceWorker(buildId),
    "utf8",
  );
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  await generate();
}
